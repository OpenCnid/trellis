import { countOccurrences, sectionContaining, sectionContainingBy, sentenceContaining } from './ground_truth';
import { chronicleAnomalyPhrase, parseLedgerRecords, type LedgerDoc } from './synthetic_corpus';
import {
  buildGuildIndex,
  guildProfile,
  parseRegistryRecords,
  type RelationalCorpus,
} from './relational_corpus';

// Session 28 (roadmap §4 row 6): the sufficiency-bounded question set
// for the estimation-discipline positive control — the module's
// RESEARCH.md control design turned into probe questions. Every truth
// is COMPUTED from committed or deterministically generated bytes (the
// ground_truth house pattern, unit-pinned in estimation_suite.test.ts),
// and every question carries a recorded MINIMAL-EVIDENCE BOUND: the
// number of database tool calls a disciplined run needs. The bound is
// documentation for the measurement — printed and recorded, never an
// assertion on a run, and never a reward for low call counts alone
// (Guardrail 4: the criterion is fewer calls WITH non-inferior
// correctness, reported together).
//
// Design shape: two-part questions whose parts share ONE read (the
// repeat-retrieval pressure the module targets — probe round 1's 8-vs-4
// repeated external calls), over the four durable probe corpora only.
// Distinctness of every scored value pair is enforced loudly at truth
// time — two equal integers would make the token-match scoring
// trivially satisfiable.

export const EST_CHRONICLE_NEEDLES = ['Kelvorin', 'Torulf'] as const;
export const EST_CHRONICLE_ANOMALY = 8;
export const EST_FRANK_PHRASE = 'It was on a dreary night of November';
export const EST_FRANK_NEEDLE = 'Ingolstadt';
export const EST_LEDGER_CAPTAIN = 'Zelvane Wendrick';
export const EST_LEDGER_MATERIAL = 'morrowleaf';
export const EST_REL_GUILD = 'Glasswind';

/**
 * The recorded minimal-evidence bound per question id: how many
 * database tool calls a disciplined run needs. Rationale, per id:
 *
 * - est-chr-counts:        one get_ast_texts of the chronicle root
 *                          binds both counts.
 * - est-chr-quote-entry:   one get_ast_blocks of the chronicle root
 *                          binds the sentence AND its entry (blocks
 *                          carry text and structure together).
 * - est-frank-locate-count: one get_ast_blocks of the frank root binds
 *                          the section and, by joining block texts, the
 *                          whole-document count.
 * - est-led-captain:       one get_ast_texts with the LIST of all 40
 *                          ledger roots binds both parts.
 * - est-rel-guild:         one get_ast_texts with the LIST of the
 *                          registry root plus all 100 ledger roots
 *                          binds the join and both aggregates.
 */
export const EST_MIN_EVIDENCE_CALLS: Readonly<Record<string, number>> = {
  'est-chr-counts': 1,
  'est-chr-quote-entry': 1,
  'est-frank-locate-count': 1,
  'est-led-captain': 1,
  'est-rel-guild': 1,
};

/** Both chronicle needle counts; equal counts are a design error. */
export function estChronicleCounts(chronicle: string): { first: number; second: number } {
  const [a, b] = EST_CHRONICLE_NEEDLES;
  const first = countOccurrences(chronicle, a);
  const second = countOccurrences(chronicle, b);
  if (first === second) {
    throw new Error(
      `[est] Needle counts for "${a}" and "${b}" are both ${first}; `
      + 'two equal integers cannot anchor a two-part count question.'
    );
  }
  return { first, second };
}

/** The anomaly sentence and its entry; one shared get_ast_blocks read binds both. */
export function estChronicleQuoteEntry(chronicle: string): {
  phrase: string;
  sentence: string;
  entry: string;
} {
  const phrase = chronicleAnomalyPhrase(EST_CHRONICLE_ANOMALY);
  const sentence = sentenceContaining(chronicle, phrase);
  const entry = sectionContainingBy(chronicle, phrase, ['Entry']);
  // The answer is scored on its FIRST "Entry N" token; a sentence that
  // itself carries one would make the lead claim ambiguous.
  if (/\bEntry\s+\d/.test(sentence)) {
    throw new Error(
      `[est] The anomaly-${EST_CHRONICLE_ANOMALY} sentence carries an "Entry N" reference; `
      + 'pick a different anomaly.'
    );
  }
  return { phrase, sentence, entry };
}

/** The frank section of the phrase plus the whole-document needle count. */
export function estFrankLocateCount(frank: string): { section: string; count: number } {
  const section = sectionContaining(frank, EST_FRANK_PHRASE);
  const count = countOccurrences(frank, EST_FRANK_NEEDLE);
  const sectionNumber = Number(section.split(' ')[1]);
  if (count === sectionNumber) {
    throw new Error(
      `[est] The ${EST_FRANK_NEEDLE} count equals the section number (${count}); `
      + 'the two-part scoring would be trivially satisfiable.'
    );
  }
  return { section, count };
}

/** Captain-material total plus how many ledgers carry that pair. */
export function estLedgerCaptainMaterial(docs: readonly LedgerDoc[]): {
  total: number;
  ledgersWith: number;
} {
  let total = 0;
  let ledgersWith = 0;
  for (const doc of docs) {
    const own = parseLedgerRecords(doc.text).filter(
      r => r.captain === EST_LEDGER_CAPTAIN && r.material === EST_LEDGER_MATERIAL
    );
    if (own.length > 0) ledgersWith += 1;
    total += own.reduce((sum, r) => sum + r.crates, 0);
  }
  if (ledgersWith === 0) {
    throw new Error(
      `[est] No ledger records Captain ${EST_LEDGER_CAPTAIN} shipping `
      + `${EST_LEDGER_MATERIAL}; pick a different pair.`
    );
  }
  if (total === ledgersWith) {
    throw new Error('[est] Ledger total equals the ledger count; redesign the question.');
  }
  return { total, ledgersWith };
}

/** Guild crate total plus distinct shipping captains (the registry join). */
export function estRelationalGuild(corpus: RelationalCorpus): {
  crates: number;
  captainCount: number;
} {
  const registry = parseRegistryRecords(corpus.registry.text);
  const guildIndex = buildGuildIndex(registry);
  const records = corpus.ledgers.flatMap(d => parseLedgerRecords(d.text));
  const profile = guildProfile(records, guildIndex, EST_REL_GUILD);
  if (profile.crates === profile.captainCount) {
    throw new Error('[est] Guild crates equal the captain count; redesign the question.');
  }
  return { crates: profile.crates, captainCount: profile.captainCount };
}
