// Session 22 (pillar §6.3 round 2): deterministic synthetic corpora for
// the effective-context probe.
//
// Round 1's corpus (Frankenstein) is in every model's training data, so
// its quote and localization answers might come from parametric memory
// rather than from reading the REPL structure. These corpora exist
// nowhere outside this repository:
//
//   1. THE CHRONICLE — one large document (invented proper nouns,
//      template prose, one planted unique "anomaly" sentence per entry)
//      committed as data/synthetic_chronicle.txt. Counting stays the
//      memorization-immune control; quote/locate questions over planted
//      anomalies are unanswerable from memory — they isolate true
//      read-fidelity through the REPL.
//   2. THE LEDGERS — many small documents whose single canonical record
//      shape ("On day D, Captain X Y shipped N crates of M to Port P.")
//      makes cross-document filtering and aggregation computable from
//      bytes. This is the multi-file regime where the pillar's §7 claims
//      a DataFrame earns its place; whether the model reaches for one is
//      the measurement, not a requirement.
//
// Everything here is pure and seeded (mulberry32 over integer ops —
// bit-identical on every platform); the generated bytes are pinned by
// sha256 in synthetic_corpus.test.ts, and the chronicle must equal the
// committed file byte-for-byte. Ground truth is still COMPUTED from the
// bytes by the ground_truth helpers at probe time — the generator's own
// bookkeeping never becomes an expected answer (the T13 posture applied
// to measurement). ASCII only: no encoding ambiguity on any checkout.

// --- Seeded RNG --------------------------------------------------------------

/** mulberry32: deterministic 32-bit PRNG (integer ops + one division). */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export class Rng {
  private readonly next: () => number;
  constructor(seed: number) {
    this.next = mulberry32(seed);
  }
  /** Integer in [lo, hi] inclusive. */
  int(lo: number, hi: number): number {
    return lo + Math.floor(this.next() * (hi - lo + 1));
  }
  pick<T>(items: readonly T[]): T {
    return items[this.int(0, items.length - 1)];
  }
}

