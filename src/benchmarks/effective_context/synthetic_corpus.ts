// --- The chronicle ------------------------------------------------------------

export const CHRONICLE_SEED = 0x22c0ffee;
export const CHRONICLE_ENTRIES = 48;
export const CHRONICLE_SECTION_KINDS = ['Entry'] as const;

interface SentenceContext {
  rng: Rng;
}

// Template prose: paragraphs are emitted as SINGLE LINES (no hard
// wrapping), so a sentence's raw bytes equal its whitespace-normalized
// form — byte-fidelity questions and edit-arm splices stay unambiguous.
const TEMPLATES: ReadonlyArray<(c: SentenceContext) => string> = [
  c => `${c.rng.pick(PERSONS)} carried ${c.rng.int(2, 97)} bundles of ${c.rng.pick(MATERIALS)} across the ${c.rng.pick(PLACES)} causeway before dusk.`,
  c => `At first light, ${c.rng.pick(PERSONS)} argued with ${c.rng.pick(PERSONS)} over the price of ${c.rng.pick(MATERIALS)}.`,
  c => `The wardens of ${c.rng.pick(PLACES)} recorded ${c.rng.int(2, 97)} barrels of ${c.rng.pick(MATERIALS)} in the lower vault.`,
  c => `${c.rng.pick(PERSONS)} wrote that the roads to ${c.rng.pick(PLACES)} stayed flooded for ${c.rng.int(2, 19)} days.`,
  c => `A courier from ${c.rng.pick(PLACES)} brought word that ${c.rng.pick(PERSONS)} had recovered from the marsh fever.`,
  c => `${c.rng.pick(PERSONS)} traded ${c.rng.int(2, 97)} measures of ${c.rng.pick(MATERIALS)} for a mule and a river map of ${c.rng.pick(PLACES)}.`,
  c => `Nothing else of note passed, though ${c.rng.pick(PERSONS)} counted ${c.rng.int(2, 97)} lanterns along the ${c.rng.pick(PLACES)} wall.`,
  c => `${c.rng.pick(PERSONS)} accused ${c.rng.pick(PERSONS)} of hoarding ${c.rng.pick(MATERIALS)}, and the circuit council fined them both.`,
  c => `The ${c.rng.pick(PLACES)} ferry went down with ${c.rng.int(2, 97)} crates of ${c.rng.pick(MATERIALS)}, and ${c.rng.pick(PERSONS)} salvaged what the river left.`,
  c => `${c.rng.pick(PERSONS)} taught the apprentices to grade ${c.rng.pick(MATERIALS)} by lamplight until the third bell.`,
  c => `Rain kept the ${c.rng.pick(PLACES)} road empty, so ${c.rng.pick(PERSONS)} mended nets and said little.`,
  c => `A dispute over ${c.rng.int(2, 97)} weights of ${c.rng.pick(MATERIALS)} was settled when ${c.rng.pick(PERSONS)} produced the older tally.`,
  c => `${c.rng.pick(PERSONS)} sent ${c.rng.int(2, 97)} sealed jars of ${c.rng.pick(MATERIALS)} up the ${c.rng.pick(PLACES)} locks.`,
  c => `The almanac keeper at ${c.rng.pick(PLACES)} certified the harvest of ${c.rng.pick(MATERIALS)} as middling.`,
] as const;

function anomalySentence(relic: string, lostPlace: string): string {
  // The anchor phrase sits mid-sentence in its exact lowercase form so
  // chronicleAnomalyPhrase matches the bytes case-sensitively.
  return `It is recorded that the ${relic} of ${lostPlace} was catalogued under the pale seal and never spoken of again.`;
}

/** The unique phrase a quote/locate question anchors on for entry i. */
export function chronicleAnomalyPhrase(entryIndex: number): string {
  return `the ${RELICS[entryIndex]} of ${LOST_PLACES[entryIndex]}`;
}

/**
 * Generates the chronicle deterministically. The committed
 * data/synthetic_chronicle.txt must equal the returned text
 * byte-for-byte (pinned by the unit test); the probe reads the
 * committed file, not this function, so a drifted generator fails
 * loudly instead of silently moving the corpus. Anomaly i (0-based,
 * chronicleAnomalyPhrase(i)) is planted in entry i+1 — but the probe
 * still LOCATES it from the bytes, never from this arithmetic.
 */
export function generateChronicle(): string {
  if (CHRONICLE_ENTRIES > RELICS.length || CHRONICLE_ENTRIES > LOST_PLACES.length) {
    throw new Error('Not enough reserved anomaly vocabulary for the entry count.');
  }
  const rng = new Rng(CHRONICLE_SEED);
  const parts: string[] = [];
  parts.push('The Chronicle of the Ninth Circuit Archive');
  parts.push(
    'Being the season records of the circuit houses, set down by the duty '
    + 'keepers in the plain style, one entry to a sitting, and bound for the '
    + 'archive at the turn of each year.'
  );

  for (let entry = 1; entry <= CHRONICLE_ENTRIES; entry++) {
    parts.push(`Entry ${entry}`);
    const paragraphCount = rng.int(13, 19);
    const anomalyParagraph = rng.int(2, paragraphCount - 1);
    for (let p = 1; p <= paragraphCount; p++) {
      const sentences: string[] = [];
      const sentenceCount = rng.int(3, 6);
      for (let s = 0; s < sentenceCount; s++) {
        sentences.push(rng.pick(TEMPLATES)({ rng }));
      }
      if (p === anomalyParagraph) {
        // Planted mid-paragraph: unanswerable from memory, and never a
        // paragraph-initial sentence a lazy heuristic could find.
        sentences.splice(
          Math.min(1, sentences.length - 1), 0,
          anomalySentence(RELICS[entry - 1], LOST_PLACES[entry - 1])
        );
      }
      parts.push(sentences.join(' '));
    }
  }
  return parts.join('\n\n') + '\n';
}

// --- The ledgers ----------------------------------------------------------------

export const LEDGER_SEED = 0x22bead5;
export const LEDGER_HOUSE_COUNT = 40;
export const LEDGER_DOC_KEY_PREFIX = 'ledger:synthetic:house-';

export interface LedgerDoc {
  /** Two-digit house number, '01'..'40'. */
  house: string;
  docKey: string;
  text: string;
}

export interface LedgerRecord {
  day: number;
  captain: string;
  crates: number;
  material: string;
  port: string;
}

function captainPool(rng: Rng): string[] {
  // 22 two-part captain names drawn from the person pool without reuse
  // of a first name, shared across every ledger so cross-document
  // aggregation by captain is meaningful.
  const firsts = [...PERSONS];
  const pool: string[] = [];
  while (pool.length < 22 && firsts.length > 1) {
    const first = firsts.splice(rng.int(0, firsts.length - 1), 1)[0];
    let last = first;
    while (last === first) last = rng.pick(PERSONS);
    pool.push(`${first} ${last}`);
  }
  return pool;
}

function renderRecord(r: LedgerRecord): string {
  return `On day ${r.day}, Captain ${r.captain} shipped ${r.crates} crates of ${r.material} to ${r.port}.`;
}

/** Generates the full ledger set deterministically (one seed, one pass). */
export function generateLedgers(): LedgerDoc[] {
  const rng = new Rng(LEDGER_SEED);
  const captains = captainPool(rng);
  const docs: LedgerDoc[] = [];
  for (let h = 1; h <= LEDGER_HOUSE_COUNT; h++) {
    const house = String(h).padStart(2, '0');
    const recordCount = rng.int(45, 65);
    const records: LedgerRecord[] = [];
    for (let i = 0; i < recordCount; i++) {
      records.push({
        day: rng.int(1, 90),
        captain: rng.pick(captains),
        crates: rng.int(5, 99),
        material: rng.pick(MATERIALS),
        port: rng.pick(PORTS),
      });
    }
    records.sort((a, b) => a.day - b.day || a.captain.localeCompare(b.captain));
    const lines: string[] = [
      `Shipping ledger ${house} of the Ninth Circuit trading season.`,
      '',
    ];
    records.forEach((r, i) => {
      lines.push(renderRecord(r));
      // Paragraph breaks every ~6 records keep blocks parser-friendly.
      if ((i + 1) % 6 === 0 && i + 1 < records.length) lines.push('');
    });
    docs.push({
      house,
      docKey: `${LEDGER_DOC_KEY_PREFIX}${house}`,
      text: lines.join('\n') + '\n',
    });
  }
  return docs;
}

const RECORD_SHAPE =
  /On day (\d+), Captain ([A-Za-z]+ [A-Za-z]+) shipped (\d+) crates of ([a-z]+) to (Port [A-Za-z]+)\./g;

/**
 * Parses ledger records back OUT OF TEXT — the representation-invariant
 * ground-truth path: the same parse runs over the generated bytes and
 * over the database reconstruction, and the probe's expected answers are
 * computed from what the parse returns, never from generator bookkeeping.
 *
 * The parse is SHAPE-based (a global regex), not line-based: the AST
 * reconstruction concatenates paragraph blocks with unmarked boundaries
 * (found live at Session 22 ingest — the last record of one block glues
 * directly onto the first record of the next), so line splitting is not
 * representation-invariant but the record shape is. Every "On day "
 * occurrence must belong to a well-formed record; a mismatch is a
 * corpus-design error, thrown.
 */
export function parseLedgerRecords(text: string): LedgerRecord[] {
  const matches = [...text.matchAll(RECORD_SHAPE)];
  const attempts = countMarker(text, 'On day ');
  if (matches.length !== attempts) {
    throw new Error(
      `Malformed ledger record: ${attempts} "On day " marker(s) but only `
      + `${matches.length} well-formed record(s).`
    );
  }
  return matches.map(match => ({
    day: Number(match[1]),
    captain: match[2],
    crates: Number(match[3]),
    material: match[4],
    port: match[5],
  }));
}

function countMarker(text: string, marker: string): number {
  let count = 0;
  let index = text.indexOf(marker);
  while (index !== -1) {
    count++;
    index = text.indexOf(marker, index + marker.length);
  }
  return count;
}

/** Total crates of a material per port, across a record set. */
export function totalsByPort(records: readonly LedgerRecord[], material: string): Map<string, number> {
  const totals = new Map<string, number>();
  for (const r of records) {
    if (r.material !== material) continue;
    totals.set(r.port, (totals.get(r.port) ?? 0) + r.crates);
  }
  return totals;
}

/**
 * The single port receiving the largest total of a material. A tie
 * cannot anchor a question and is refused loudly (question-design error,
 * the sentenceContaining posture).
 */
export function topPortForMaterial(
  records: readonly LedgerRecord[],
  material: string
): { port: string; total: number } {
  const totals = [...totalsByPort(records, material).entries()].sort((a, b) => b[1] - a[1]);
  if (totals.length === 0) throw new Error(`No records for material "${material}".`);
  if (totals.length > 1 && totals[0][1] === totals[1][1]) {
    throw new Error(
      `Tie for top port of "${material}" (${totals[0][0]} and ${totals[1][0]} at ${totals[0][1]}); `
      + 'pick a different material.'
    );
  }
  return { port: totals[0][0], total: totals[0][1] };
}

/** Total crates of a material shipped by one captain across all records. */
export function totalForCaptainMaterial(
  records: readonly LedgerRecord[],
  captain: string,
  material: string
): number {
  return records
    .filter(r => r.captain === captain && r.material === material)
    .reduce((sum, r) => sum + r.crates, 0);
}

